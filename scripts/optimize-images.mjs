// Dev-only: writes WebP copies of the site's photos and regenerates src/data/photos.js.
// Usage: node scripts/optimize-images.mjs   (originals are never modified)
import { readdir, stat, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(root, 'public');
const photoDir = path.join(pub, 'images', 'joel-photography');
const PHOTO_RE = /^photo-(\d+)\.jpe?g$/i;

async function mtime(file) {
  try {
    return (await stat(file)).mtimeMs;
  } catch {
    return 0;
  }
}

async function size(file) {
  return (await stat(file)).size;
}

/** Resize (never enlarge), honour EXIF orientation, write WebP. Skips outputs newer than the source. */
async function toWebp(src, out, width, quality) {
  await mkdir(path.dirname(out), { recursive: true });
  const rel = path.relative(root, out);
  if ((await mtime(out)) > (await mtime(src))) {
    const meta = await sharp(out).metadata();
    console.log(`skip  ${rel}  ${meta.width}x${meta.height}`);
    return meta;
  }
  const info = await sharp(src).rotate().resize({ width, withoutEnlargement: true }).webp({ quality }).toFile(out);
  console.log(`write ${rel}  ${info.width}x${info.height}`);
  return info;
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => {
      const full = path.join(dir, e.name);
      return e.isDirectory() ? walk(full) : [full];
    }),
  );
  return files.flat();
}

async function photography() {
  const ids = (await readdir(photoDir))
    .map((f) => PHOTO_RE.exec(f))
    .filter(Boolean)
    .map((m) => ({ id: Number(m[1]), file: m[0] }))
    .sort((a, b) => b.id - a.id); // newest first

  let before = 0;
  let after = 0;
  const rows = [];
  for (const { id, file } of ids) {
    const src = path.join(photoDir, file);
    const thumbOut = path.join(photoDir, 'thumbs', `photo-${id}.webp`);
    const largeOut = path.join(photoDir, 'large', `photo-${id}.webp`);
    const smallOut = path.join(photoDir, 'thumbs-sm', `photo-${id}.webp`);
    await toWebp(src, thumbOut, 640, 72);
    await toWebp(src, smallOut, 320, 70);
    const large = await toWebp(src, largeOut, 1600, 80);
    before += await size(src);
    after += (await size(thumbOut)) + (await size(largeOut));
    rows.push({ id, file, width: large.width, height: large.height });
  }

  const body = rows
    .map(
      (r) =>
        `  { id: ${r.id}, thumb: '/images/joel-photography/thumbs/photo-${r.id}.webp', thumbSm: '/images/joel-photography/thumbs-sm/photo-${r.id}.webp', large: '/images/joel-photography/large/photo-${r.id}.webp', original: '/images/joel-photography/${r.file}', width: ${r.width}, height: ${r.height}, alt: 'Photograph ${r.id} by Joel Leiva' },`,
    )
    .join('\n');
  const mod = `// Generated by scripts/optimize-images.mjs. Do not edit by hand; re-run the script after adding photos.
// Newest first. width/height are the dimensions of the large WebP.
export const photos = [
${body}
];
`;
  await writeFile(path.join(root, 'src', 'data', 'photos.js'), mod);

  const mb = (n) => `${(n / 1024 / 1024).toFixed(1)} MB`;
  console.log(`\nphotography: ${rows.length} photos, originals ${before} B (${mb(before)}), WebP thumbs + large ${after} B (${mb(after)})`);
}

async function siblings() {
  const portraits = (await readdir(path.join(pub, 'images', 'joel-photos')))
    .filter((f) => /\.jpe?g$/i.test(f))
    .map((f) => path.join(pub, 'images', 'joel-photos', f));
  const projectImages = (await walk(path.join(pub, 'projects'))).filter((f) => /\.(jpe?g|png)$/i.test(f));
  for (const src of [...portraits, ...projectImages]) {
    const out = src.replace(/\.(jpe?g|png)$/i, '.webp');
    await toWebp(src, out, 1200, 80);
  }
}

await photography();
await siblings();
